"""fig_dpo_logprob_dist.png  (Claim 4.4 — the aggressive-fine-tune boundary).

Two overlaid histograms: per-token log-probability of held-out base-distribution structures
under the BASE model vs the aggressively fine-tuned (DPO/IPO) model. Mark the uniform-vocab
baseline (-log 16000 = -9.70). Fine-tuned mass below uniform ⇒ off the base support.

Held-out base structures = fresh samples GENERATED by the base model itself (so they are
base-distribution and correctly encoded for both models, since the DPO model was fine-tuned
from this base and shares its tokenizer). We then score the same token sequences under each.

NEEDS CHECKPOINTS (not in this data-light repo). Set:
    CUES_BASE_CKPT  -> base model dir (e.g. the production checkpoint dir)
    CUES_DPO_CKPT   -> the fine-tuned DPO checkpoint .pt
and run with the same env as score.py (HF_TOKEN; one venv). Output -> figures/.

CAVEAT (provenance): the paper's figure uses the IPO-novelty checkpoint; that checkpoint and
its training data were lost with the original box. This script was run with base = production
and DPO = a stand-in (`checkpoints_dpo_ox`). Because the held-out set is the base model's own
generations, the base distribution piles up near 0 (the base is near-certain on its own
samples); the qualitative off-support result (DPO mass ≈ -15, below the -9.7 uniform line)
holds regardless. For a moderate base distribution, use a real held-out set in the base
model's encoding instead of self-generations.
"""
